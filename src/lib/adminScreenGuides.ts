export function getAdminScreenGuide(pathname: string): AdminScreenGuide | null {
  if (ADMIN_SCREEN_GUIDES[pathname]) return ADMIN_SCREEN_GUIDES[pathname];

  const normalized = pathname.replace(/\/$/, '');
  if (ADMIN_SCREEN_GUIDES[normalized]) return ADMIN_SCREEN_GUIDES[normalized];

  return null;
}
