export function getRoleScreenGuide(path: string): AdminScreenGuide | null {
  if (ROLE_SCREEN_GUIDES[path]) return ROLE_SCREEN_GUIDES[path];

  const normalized = path.replace(/\/$/, '');
  if (ROLE_SCREEN_GUIDES[normalized]) return ROLE_SCREEN_GUIDES[normalized];

  // مسارات ديناميكية
  if (path.startsWith('/principal/student/')) return ROLE_SCREEN_GUIDES['/principal/student/:studentId'] ?? null;
  if (path.startsWith('/student/exams/') && path !== '/student/exams') {
    return ROLE_SCREEN_GUIDES['/student/exams/:examId'] ?? null;
  }
  if (path.startsWith('/analytics/')) {
    const tab = path.replace('/analytics/', '');
    const key = `/analytics/${tab}`;
    return ROLE_SCREEN_GUIDES[key] ?? null;
  }

  return null;
}

export function getAnyScreenGuide(path: string): AdminScreenGuide | null {
  // يُستورد من userGuides مع adminScreenGuides
  return getRoleScreenGuide(path);
}
